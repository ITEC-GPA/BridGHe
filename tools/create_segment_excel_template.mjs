// Author the embedded workbook once; the plugin fills it using its existing OOXML support.
// node create_segment_excel_template.mjs <bundled node_modules directory>
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { Workbook, SpreadsheetFile } = await import(pathToFileURL(require.resolve('@oai/artifact-tool')).href);
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('Sezioni');
sheet.showGridLines = false;
sheet.getRange('A1:J7').format.font = { name: 'Arial', size: 10, color: '#203745' };
sheet.getRange('A1:J7').format.rowHeight = 24;
sheet.getRange('A2').values = [['BridGHe — sezioni dei conci']];
sheet.getRange('A2').format.font = { name: 'Arial', size: 15, bold: true, color: '#203745' };
sheet.getRange('A3').values = [['Numero e identificativi dei conci ricavati dalla geometria. Tutte le dimensioni in mm.']];
sheet.getRange('A4').values = [['Celle gialle: dimensioni modificabili. * eredita la corrispondente dimensione della Base Property in GH.']];
sheet.getRange('A5').values = [['ID e progressive: mantenerli associati alla stessa riga. Dopo le modifiche salvare Excel e premere Run in modalità Read.']];
sheet.getRange('A6:J6').values = [['ID','s_inizio_mm','s_fine_mm','b_inf_mm','b_sup_mm','h_mm','t_inf_mm','t_sup_mm','tw_mm','r_mm']];
sheet.getRange('A6:J6').format = { fill: '#203B50', font: {name:'Arial',size:10,bold:true,color:'#FFFFFF'}, rowHeight:30, horizontalAlignment:'center', verticalAlignment:'center' };
sheet.getRange('A7:J7').values = [['G1-C1',0,12000,'*','*','*','*','*','*','*']];
sheet.getRange('A7:C7').format.fill = '#EDF1F5';
sheet.getRange('D7:J7').format.fill = '#FFF2CC';
sheet.getRange('B7:J7').setNumberFormat('0.000');
sheet.getRange('B7:J7').format.horizontalAlignment = 'right';
sheet.getRange('A1:A7').format.columnWidth = 18;
sheet.getRange('B1:C7').format.columnWidth = 19;
sheet.getRange('D1:J7').format.columnWidth = 15;
sheet.freezePanes.freezeRows(6);
workbook.recalculate();
console.log((await workbook.inspect({kind:'table',range:'Sezioni!A6:J7',include:'values,formulas',tableMaxRows:2,tableMaxCols:10})).ndjson);
const folder = path.resolve('src/BridGHe.Common/Resources');
await fs.mkdir(folder,{recursive:true});
const file = await SpreadsheetFile.exportXlsx(workbook);
await file.save(path.join(folder,'BridgeSegmentSections.xlsx'));
await fs.mkdir('artifacts/segment-excel',{recursive:true});
const preview = await workbook.render({sheetName:'Sezioni',range:'A1:J8',scale:1.5,format:'png'});
await fs.writeFile('artifacts/segment-excel/template.png',new Uint8Array(await preview.arrayBuffer()));
console.log('SEGMENT EXCEL TEMPLATE PASS');
