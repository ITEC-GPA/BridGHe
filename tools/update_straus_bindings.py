"""Extract only the R3 API declarations used by BridGHe from the installed vendor header."""
from pathlib import Path
import re,hashlib,json
root=Path(__file__).resolve().parents[1]
header=Path(r'C:\Program Files\Straus7 R31\API Includes\Visual C#\St7API.cs')
source=header.read_text(encoding='utf-8-sig')
target=root/'src/BridGHe.Common/Helpers/St7API.cs'
used=set()
for base in ('src','tests'):
    for p in (root/base).rglob('*.cs'):
        if p!=target and not {'bin','obj'}&set(p.parts):used.update(re.findall(r'\bSt7\.(\w+)',p.read_text(encoding='utf-8-sig')))
constants={m.group(1):m.group(0) for m in re.finditer(r'public const \w+ (\w+)\s*=[^;]+;',source)}
functions={m.group(1):m.group(0) for m in re.finditer(r'\[DllImport\([^\n]+\)\]\s*public static extern \w+ (\w+)\([^;]+;',source)}
previous=set()
while used!=previous:
    previous=used.copy()
    for key in previous:
        if key in constants:used.update(set(re.findall(r'\b\w+\b',constants[key].split('=',1)[1]))&constants.keys())
missing=used-constants.keys()-functions.keys()
if missing:raise ValueError(missing)
lines=['// Generated by tools/update_straus_bindings.py from the installed Straus7 R3 header.','// Do not hand-edit signatures or array marshalling.','using System;','using System.Runtime.InteropServices;','using System.Text;','namespace St7API','{','    public static class St7','    {']
for declarations in (constants,functions):
    for key,definition in declarations.items():
        if key in used:lines.append('        '+definition.replace('\n        ','\n        '))
lines+=['    }','}'];target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
(root/'migration/straus-api-source.json').write_text(json.dumps({'source':str(header),'sha256':hashlib.sha256(header.read_bytes()).hexdigest(),'declarations':len(used),'functions':len(used&functions.keys())},indent=2),encoding='utf-8')
print(f'Extracted {len(used)} declarations')
