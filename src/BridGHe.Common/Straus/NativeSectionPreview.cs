using System;
using System.IO;
using System.Linq;
using Rhino.Geometry;
using St7API;

namespace BridGHe.Common.Straus;

/// <summary>Display-only boundary sampled from the vendor's section mesh. Never used for stiffness.</summary>
internal static class NativeSectionPreview
{
    internal static double[][] Read(int source,int property)
    {
        string directory=Path.Combine(Path.GetTempPath(),"BridGHe",Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);int id=StrausRuntime.AcquireModelId();bool open=false;
        try
        {
            string file=Path.Combine(directory,"preview.st7");
            StrausRuntime.Check(St7.St7SaveBeamSectionMesh(source,property,file),"St7SaveBeamSectionMesh");
            StrausRuntime.Check(St7.St7OpenFile(id,file,directory+Path.DirectorySeparatorChar),"Open section preview");open=true;
            int nodes=0,plates=0;
            StrausRuntime.Check(St7.St7GetTotal(id,St7.tyNODE,ref nodes),"Preview node count");
            StrausRuntime.Check(St7.St7GetTotal(id,St7.tyPLATE,ref plates),"Preview plate count");
            using var mesh=new Mesh();var xyz=new double[3];
            // The section mesh generated by Straus has consecutive node/plate numbering.
            for(int i=1;i<=nodes;i++)
            {
                StrausRuntime.Check(St7.St7GetNodeXYZ(id,i,xyz),"Preview node");mesh.Vertices.Add(xyz[0],xyz[1],xyz[2]);
            }
            var connection=new int[St7.kMaxElementNode+1];
            for(int i=1;i<=plates;i++)
            {
                StrausRuntime.Check(St7.St7GetElementConnection(id,St7.tyPLATE,i,connection),"Preview connectivity");
                if(connection[0]==3||connection[0]==6)mesh.Faces.AddFace(connection[1]-1,connection[2]-1,connection[3]-1);
                else if(connection[0]==4||connection[0]==8||connection[0]==9)mesh.Faces.AddFace(connection[1]-1,connection[2]-1,connection[3]-1,connection[4]-1);
                else throw new NotSupportedException("Unsupported native section preview plate: "+connection[0]);
            }
            // Mesh geometry is display data; centre it on its own area centroid. Native section
            // properties and the native principal-axis rotation remain the sole analysis inputs.
            using var area=AreaMassProperties.Compute(mesh);
            if(area==null||area.Area<=0)throw new InvalidOperationException("Empty native section preview mesh.");
            var center=area.Centroid;
            return mesh.GetNakedEdges().Select(loop=>loop.SelectMany(p=>new[]{p.X-center.X,p.Y-center.Y}).ToArray()).ToArray();
        }
        finally
        {
            if(open)St7.St7CloseFile(id);StrausRuntime.ReleaseModelId(id);
            try { Directory.Delete(directory,true); } catch(IOException) { } catch(UnauthorizedAccessException) { }
        }
    }
}
