using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using BridGHe.Common.Gpc.Legacy;
using BridGHe.Common.MovingLoads;
using GPC.Model.LoadCases;
using GPC.Model.Loads;

namespace BridGHe.Common.Gpc
{
    /// <summary>
    /// F6 chain D: the model transformers of the components on GPC. Each builds the GPC input of its output from the GPC input of its source
    /// (a copy, never a conversion of the FEM output), with the semantics of the former FEM transformer and of the legacy reader that
    /// converted its output, so that the analysis runs on the same GPC model (checked bit for bit by the tests against the conversion of the
    /// FEM output). The copy keeps the element identities of the source (cases by name).
    /// <para>Identity: a transformed model is a new model with its own model GUID (<c>modelIdentity</c>, from the component;
    /// `ModelValues.Copy(model, options, identity)`, L11) and the element identities of its source.</para>
    /// <para>Cases: the legacy reader places every case at its first origin (<see cref="LegacyCaseOrigins"/>: registered, element loads,
    /// combinations, stage increments, moving paths, default "Dead"); a transformer updates the origins of its source
    /// (<see cref="LegacyImportReport.CaseOrigins"/>) and orders the cases as the reader would on its FEM output.</para>
    /// </summary>
    public static class GpcModelTransforms
    {
        private const LegacyCaseOrigins Defined = LegacyCaseOrigins.Registered | LegacyCaseOrigins.ElementLoad | LegacyCaseOrigins.Combination | LegacyCaseOrigins.Stage;

        /// <summary>Attach Moving Paths (former <see cref="MovingModelBuilder.ReplacePaths"/>): the moving paths of the model replaced by
        /// <paramref name="paths"/>; the cases of new paths are registered after the cases registered in the model (as the former transformer
        /// did); the static cases generated by a former moving analysis are not input cases of a conversion (nothing to remove). A case
        /// only the replaced paths referred to goes, as in the conversion of the former output, unless the former model registered it.</summary>
        public static GpcModels.Conversion ReplacePaths(GpcModels.Conversion input, IReadOnlyList<MovingPath> paths, Guid modelIdentity)
        {
            if (input == null) throw new ArgumentNullException(nameof(input));
            if (paths == null || paths.Any(p => p == null)) throw new ArgumentException("MovingPathsRequired");
            var clones = paths.Select(p => { p.Validate(); return (MovingPath)p.Clone(); }).ToList();
            var model = GPC.Model.Core.ModelValues.Copy(input.Model, GPC.Model.Core.ModelCopyOptions.None, modelIdentity);
            // The moving data of a conversion: the definition and its records (path options, library data, centrifugal records).
            model.MovingLoads = null; model.PreservedSourceData.Clear();
            // Cases in the order of the legacy reader: those registered in the model (the former transformer registers the case of every
            // new path after them), then those of element loads, combinations and stages; the cases only the replaced paths referred to go,
            // as in the conversion of the former output; the default "Dead" last.
            var origins = Origins(input.Report);
            foreach (var name in origins.Keys.ToList()) origins[name] &= ~LegacyCaseOrigins.Moving;
            var cases = model.LoadCases.Values.ToList();
            int count = Math.Min(input.Report.RegisteredCases, cases.Count);
            var registered = cases.Take(count).ToList(); var others = cases.Skip(count).ToList();
            foreach (var path in clones)
            {
                if (!registered.Any(c => c.Name == path.LoadCaseName))
                {
                    var existing = others.FirstOrDefault(c => c.Name == path.LoadCaseName);
                    if (existing != null) others.Remove(existing);
                    registered.Add(existing ?? new LoadCaseBase(GpcIdentity.Case(path.LoadCaseName), path.LoadCaseName) { InertiaMasses = new InertiaMassSelection { Structural = false, NonStructural = false } });
                }
                origins.TryGetValue(path.LoadCaseName, out var o); origins[path.LoadCaseName] = o | LegacyCaseOrigins.Registered | LegacyCaseOrigins.Moving;
            }
            int registeredCount = registered.Count;
            SetCases(model, registered.Concat(others.Where(c => (Origin(origins, c) & (LegacyCaseOrigins.ElementLoad | LegacyCaseOrigins.Combination | LegacyCaseOrigins.Stage)) != 0)).ToList(), origins);
            if (clones.Count != 0)
                GpcMoving.FromLegacyJson(JsonSerializer.Serialize(clones), model, model.LoadCases.ToDictionary(p => p.Key, p => p.Value, StringComparer.Ordinal), input.Report.Units, input.Report.Owner);
            var report = input.Report.CopyFor(registeredCount);
            Replace(report.CaseOrigins, origins);
            return new GpcModels.Conversion(model, report, input.Tolerance);
        }

        /// <summary>Bridge Phase Model (former <see cref="Diagnostics.BridgePhaseModel.Create"/>): an independent copy named <paramref name="name"/>
        /// with the beams of <paramref name="beamIds"/> (BridGHe IDs, GPC names) on <paramref name="property"/>; combinations, stages and their
        /// freedom case always go; with <paramref name="clearLoads"/> also every load (element loads and assignments, case-dependent physical
        /// data, model loads), the moving loads and every case but the default "Dead". As the conversion of the former output:
        /// <list type="bullet">
        /// <item>beam properties registered by name in beam order, the first of a name for every beam of that name (the former exporter: a
        /// replacement with the name of another property takes or gives that property, with the warning "already exists"); properties no
        /// longer used go;</item>
        /// <item>a beam that changes property takes its formulation, its section axes (BridGHe angle of the beam, principal angle of the
        /// section; the axes of its distributed supports with them) and its native section;</item>
        /// <item>cases: registered, of element loads, then of the moving paths only, then "Dead".</item>
        /// </list></summary>
        public static GpcModels.Conversion PhaseModel(GpcModels.Conversion input, string name, IReadOnlyList<string> beamIds, LegacyBeamProperty property, bool clearLoads, Guid modelIdentity)
        {
            if (input == null) throw new ArgumentNullException(nameof(input));
            if (string.IsNullOrWhiteSpace(name)) throw new ArgumentException("Phase model name is required.");
            if (beamIds == null || beamIds.Count == 0 || beamIds.Any(string.IsNullOrWhiteSpace) || beamIds.Distinct().Count() != beamIds.Count)
                throw new ArgumentException("Supply unique, non-empty Beam IDs explicitly; no implicit whole-model override.");
            var unknown = beamIds.Except(input.Model.BeamElements.Values.Select(b => b.Name)).ToArray();
            if (unknown.Length > 0) throw new ArgumentException("Unknown Beam IDs: " + string.Join(", ", unknown));
            if (property?.Property == null || property.Data == null) throw new ArgumentException("A valid replacement beam property is required.");
            var source = input.Report;
            var model = GPC.Model.Core.ModelValues.Copy(input.Model, GPC.Model.Core.ModelCopyOptions.None, modelIdentity);
            model.Name = name;
            model.Combinations.Clear(); model.Stages.Clear(); model.FreedomCases.Clear();
            var origins = Origins(source);
            List<LoadCaseBase> order;
            var warnings = source.Warnings.Where(w => !IsExistingPropertyWarning(w)).ToList();
            if (clearLoads)
            {
                StripLoads(model); model.MovingLoads = null; model.PreservedSourceData.Clear();
                origins.Clear(); order = new List<LoadCaseBase>();
                // Warnings of the conversion about loads (node temperatures) concern the loads that go.
                warnings.RemoveAll(w => w.Contains(": temperature type ", StringComparison.Ordinal));
            }
            else
            {
                foreach (var key in origins.Keys.ToList()) origins[key] &= ~(LegacyCaseOrigins.Combination | LegacyCaseOrigins.Stage);
                var cases = model.LoadCases.Values.ToList();
                order = cases.Where(c => (Origin(origins, c) & (LegacyCaseOrigins.Registered | LegacyCaseOrigins.ElementLoad)) != 0).ToList();
                if (model.MovingLoads != null)
                    foreach (var path in model.MovingLoads.Paths)
                    {
                        var c = cases.FirstOrDefault(x => x.Guid == path.CaseGuid);
                        if (c != null && !order.Contains(c)) order.Add(c);
                    }
            }
            SetCases(model, order, origins);

            // Beam properties as the legacy reader registers them on the FEM output (one per name, first in beam order).
            var selected = beamIds.ToHashSet(StringComparer.Ordinal);
            var registry = new Dictionary<string, (GPC.Model.ElementProperties.BeamProperty Property, LegacyBeamPropertyData Data, bool Replacement)>(StringComparer.Ordinal);
            var nativeSections = new Dictionary<Guid, GPC.Converter.Straus7.Straus7SectionDefinition>(source.NativeSections);
            var shadowed = new HashSet<int>();
            foreach (var beam in model.BeamElements.Values.OrderBy(b => b.Id))
            {
                bool replaced = selected.Contains(beam.Name);
                string own = beam.BeamProperty.Name;
                if (!replaced && !source.BeamProperties.ContainsKey(own)) throw new NotSupportedException("PhaseModelSourcePropertyUnknown: " + own);
                string key = replaced ? property.Property.Name : own;
                // The digest of the former content of the property of this beam in the FEM output (unknown for a beam the source shadowed).
                string signature = replaced ? property.Data.Signature : source.ShadowedPropertyBeams.Contains(beam.Id) ? null : source.BeamProperties[own].Signature;
                if (!registry.TryGetValue(key, out var entry))
                {
                    // The first beam of a name registers its own content: unknown for a beam the source shadowed.
                    if (signature == null) throw new NotSupportedException("PhaseModelShadowedBeamProperty: " + beam.Name);
                    entry = replaced ? (property.Property, property.Data, true) : (beam.BeamProperty, source.BeamProperties[own], false);
                    registry.Add(key, entry);
                }
                else
                {
                    // A later beam of the name takes the registered property; the reader warns when its own content differs. A beam the
                    // source shadowed differs from the source property of its name (registered again here unless the replacement took the
                    // name: its own content is then unknown).
                    if (signature == null && entry.Replacement) throw new NotSupportedException("PhaseModelShadowedBeamProperty: " + beam.Name);
                    if (signature == null || signature != entry.Data.Signature) { warnings.Add(string.Format(LegacyImportReport.ExistingPropertyWarning, key)); shadowed.Add(beam.Id); }
                }
                if (ReferenceEquals(beam.BeamProperty, entry.Property)) continue;
                // A local section state (Bridge State Override) stays as it is: it names the fingerprint of the property it was computed for,
                // so on a new property it is stale and the checks refuse it ("FEM properties changed after the local section-state
                // assignment"), as with the former model (coordinator decision 3, 5/11: no conversion of the FEM output for this case). Listed
                // difference: the former model compared only the former signature of the property (A, I, J, centroid, E, nu, density, type),
                // so a replacement equal in those values (e.g. the same property under another name) kept the state current there.
                beam.BeamProperty = entry.Property;
                beam.Assignments.Formulation = entry.Data.Formulation;
                var axes = GpcBeamAxes.Section(beam.StartPoint, beam.EndPoint, source.BeamAngles[beam.Id], entry.Data.Angle);
                beam.Assignments.SectionAxes = axes;
                if (beam.Assignments.Physical != null)
                    foreach (var support in beam.Assignments.Physical.Supports)
                        support.Axes = new GPC.Geometry.CoordinateSystem(new GPC.Geometry.Point3d(0, 0, 0), axes.V1, axes.V2);
                nativeSections.Remove(beam.Guid);
                if (entry.Data.Native != null) nativeSections.Add(beam.Guid, entry.Data.Native);
            }
            model.BeamProperties.Clear();
            foreach (var entry in registry.Values) model.BeamProperties.Add(entry.Property.Name, entry.Property);

            var report = source.CopyFor(clearLoads ? 0 : source.RegisteredCases);
            Replace(report.CaseOrigins, origins);
            report.Warnings.Clear(); report.Warnings.AddRange(warnings);
            report.NativeSections.Clear(); foreach (var p in nativeSections) report.NativeSections.Add(p.Key, p.Value);
            report.BeamProperties.Clear(); foreach (var p in registry) report.BeamProperties.Add(p.Key, p.Value.Data);
            report.ShadowedPropertyBeams.Clear(); report.ShadowedPropertyBeams.UnionWith(shadowed);
            return new GpcModels.Conversion(model, report, input.Tolerance);
        }

        private static bool IsExistingPropertyWarning(string warning) =>
            warning.StartsWith("The beam property ", StringComparison.Ordinal) && warning.EndsWith(" already exists", StringComparison.Ordinal);

        /// <summary>The loads of a model removed: element loads and load assignments, case-dependent physical data (node temperatures, beam
        /// gradients and initial states, plate initial stresses and non-structural masses) and model loads; the physical data of nodes and
        /// plates that hold nothing else go, as in a conversion without loads.</summary>
        internal static void StripLoads(GPC.Model.Models.Model model)
        {
            model.ModelLoads.Clear();
            foreach (var node in model.NodesElements.Values)
            {
                node.Loads.Clear();
                var physical = node.Assignments.Physical;
                if (physical != null) { physical.Temperatures.Clear(); node.Assignments.Physical = null; }
            }
            foreach (var beam in model.BeamElements.Values)
            {
                beam.Loads.Clear(); beam.Assignments.Loads.Clear();
                var physical = beam.Assignments.Physical;
                if (physical != null) { physical.TemperatureGradients.Clear(); physical.InitialStates.Clear(); }
            }
            foreach (var plate in model.AreaElements.Values)
            {
                plate.Loads.Clear();
                var physical = plate.Assignments.Physical;
                if (physical != null)
                {
                    physical.InitialStresses.Clear(); physical.NonStructuralMasses.Clear();
                    if (physical.LoadPatch == null && physical.Supports.Count == 0) plate.Assignments.Physical = null;
                }
            }
        }

        private static Dictionary<string, LegacyCaseOrigins> Origins(LegacyImportReport report)
        {
            if (report.CaseOrigins.Count == 0) throw new NotSupportedException("GpcTransformWithoutCaseOrigins");
            return new Dictionary<string, LegacyCaseOrigins>(report.CaseOrigins, StringComparer.Ordinal);
        }

        private static LegacyCaseOrigins Origin(Dictionary<string, LegacyCaseOrigins> origins, LoadCaseBase c) => origins.TryGetValue(c.Name, out var o) ? o : LegacyCaseOrigins.None;

        private static void Replace<TKey, TValue>(Dictionary<TKey, TValue> target, Dictionary<TKey, TValue> values)
        {
            target.Clear(); foreach (var p in values) target.Add(p.Key, p.Value);
        }

        /// <summary>The cases of a transformed model: <paramref name="order"/> (cases of the model, in the order of the legacy reader on the FEM
        /// output), then the default "Dead" self-weight case when no case has that name (the model's own when it came from no case definition,
        /// else a new one: −9806.65 mm/s² along Z, structural mass); the gravity loads of the cases in the case order (renumbered as the reader
        /// numbers them when a case with gravity goes); <paramref name="origins"/> reduced to those cases.</summary>
        private static void SetCases(GPC.Model.Models.Model model, List<LoadCaseBase> order, Dictionary<string, LegacyCaseOrigins> origins)
        {
            LoadCaseBase dead = null;
            if (!order.Any(c => c.Name == "Dead"))
            {
                if (model.LoadCases.TryGetValue("Dead", out var existing) && (Origin(origins, existing) & Defined) == 0) dead = existing;
                else dead = new LoadCase(GpcIdentity.Case("Dead"), "Dead", LoadCase.LoadCaseTypes.SelfWeight) { InertiaMasses = new InertiaMassSelection { Structural = true, NonStructural = false } };
                order.Add(dead); origins["Dead"] = LegacyCaseOrigins.DefaultDead;
            }
            var gravity = model.ModelLoads.Values.ToList();
            if (gravity.Any(l => !(l is ModelGravityLoad))) throw new NotSupportedException("GpcTransformModelLoadNotGravity");
            var wanted = new List<(LoadCaseBase Case, ModelGravityLoad Load)>();
            foreach (var c in order)
            {
                var own = gravity.Where(l => ReferenceEquals(l.LoadCase, c)).Cast<ModelGravityLoad>().ToList();
                foreach (var l in own) wanted.Add((c, l));
                if (own.Count == 0 && ReferenceEquals(c, dead)) wanted.Add((c, null)); // the default self weight (its load went with the loads)
            }
            bool same = wanted.Count == gravity.Count && wanted.Select(w => w.Load).SequenceEqual(gravity);
            model.LoadCases.Clear();
            foreach (var c in order) model.LoadCases.Add(c.Name, c);
            if (!same)
            {
                model.ModelLoads.Clear();
                foreach (var (c, l) in wanted)
                    model.ModelLoads.Add(l == null ? new ModelGravityLoad(GPC.Geometry.Vector3d.ZAxis, -9806.65, c, GPC.Geometry.CoordinateSystem.Global, "Gravity Dead")
                        : new ModelGravityLoad(l.GravityVersor, l.Acceleration, c, l.CoordinateSystem, l.Name));
            }
            foreach (var key in origins.Keys.Where(k => !model.LoadCases.ContainsKey(k)).ToList()) origins.Remove(key);
        }
    }
